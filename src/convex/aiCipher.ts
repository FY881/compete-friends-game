const REVERSE_LEXICON: Record<string, string> = Object.fromEntries(
  Object.entries(CIPHER_LEXICON).map(([k, v]) => [v, k]),
);

/** هل النص يحتوي رسالة مشفرة؟ */
export function isCiphered(text: string): boolean {
  return text.includes(CIPHER_PREFIX) && text.includes(CIPHER_SUFFIX);
}

/** استخراج أجزاء الرسالة المشفرة من نص النقاش */
export function extractCipherSegments(text: string): string[] {
  const out: string[] = [];
  const re = /⟦([^⟧]*)⟧/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) out.push(m[1]);
  return out;
}

/**
 * فك الشفرة للمالك: يحوّل الرموز إلى كلماتها الأصلية.
 * يعيد نسخة مفكوكة من النص كاملاً (المشفر يُفك، والعادي يبقى).
 */
export function decipher(text: string): string {
  let out = text;
  // فك الرموز أولاً (الأطول قبل الأقصر لمنع التداخل)
  const symbols = Object.keys(REVERSE_LEXICON).sort((a, b) => b.length - a.length);
  for (const sym of symbols) {
    out = out.split(sym).join(`«${REVERSE_LEXICON[sym]}»`);
  }
  // إزالة أقواس الشفرة مع تمييز
  out = out.split(`${CIPHER_PREFIX}`).join("〔سرّ: ").split(`${CIPHER_SUFFIX}`).join("〕");
  return out;
}

