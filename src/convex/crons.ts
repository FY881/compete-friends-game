import { cronJobs } from "convex/server";
import { internal } from "./_generated/api";

// ═══════════════════════════════════════════════════════════════════════
// ⏱️ مهمة cron واحدة فقط في النظام كله — «المُوزِّع»
// ═══════════════════════════════════════════════════════════════════════
//
// لماذا واحدة؟ لأن جدولة cron في Convex **ثابتة وقت النشر**: لا يمكن
// تعديلها من قاعدة البيانات. لذلك صار التحكم الفعلي في مكان آخر:
//
//   • هذه المهمة الوحيدة تستدعي `aiCron.dispatch` كل ساعة.
//   • المُوزِّع يقرأ سجل المهام من قاعدة البيانات، ولا ينفّذ إلا
//     المهام **المفعّلة والمستحقة فقط**.
//   • فيتحكم المالك في كل مهمة AI (تفعيل/إيقاف/دورية/تشغيل فوري) من
//     غرفة المالك **لحظياً وبلا إعادة نشر**.
//
// التكلفة في الوضع الافتراضي: مُوزِّع خفيف يقرأ ~12 صفاً كل ساعة، ومهمة
// الصيانة وحدها مفعّلة (كل 24 ساعة) — أي لا استهلاك إضافي يُذكر مقارنة
// بالوضع المستقر السابق، مع تحكم كامل بدلاً من الإلغاء الكامل.
//
// يمكن للمالك إيقاف **كل شيء** بضغطة واحدة عبر «المفتاح الشامل» في
// مركز التحكم (تُحفَظ الحالة في جدول settings) — فيبقى المُوزِّع بلا
// أي عمل فعلي (قراءة واحدة) حتى يُعاد تشغيله.

const crons = cronJobs();

crons.interval(
  "ai-cron-dispatch",
  { minutes: 60 },
  internal.aiCron.dispatch,
  {},
);

export default crons;
